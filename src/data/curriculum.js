function item(id, topic, level, title, text, why, because, mentor, wonder) {
  return { id, topic, level, title, text, why, because, mentor, wonder }
}

export function worldOf(id) {
  return CURRICULUM.find((world) => world.id === id) || null
}

export function itemsOf(worldId) {
  const world = worldOf(worldId)
  return world ? world.items : []
}

export function itemById(id) {
  for (const world of CURRICULUM) {
    const found = world.items.find((entry) => entry.id === id)
    if (found) return { ...found, world: world.id, worldTitle: world.title }
  }
  return null
}

export function allItems() {
  return CURRICULUM.flatMap((world) => world.items.map((entry) => ({
    ...entry,
    world: world.id,
    worldTitle: world.title
  })))
}
